#!/usr/bin/env python3
"""Generates native/cpp/ParamIds.h and src/core/paramDefs.ts from shared/params.json.

  python3 scripts/gen_params.py          # (re)generate
  python3 scripts/gen_params.py --check  # CI: fail if the generated files are stale
"""
import json, pathlib, sys

root = pathlib.Path(__file__).resolve().parent.parent
spec = json.loads((root / "shared" / "params.json").read_text())["params"]
eng = [p for p in spec if p["engine"]]

def num(v):
    return repr(float(v)) if not float(v).is_integer() else str(int(v))

h = ["// GENERATED by scripts/gen_params.py from shared/params.json - do not edit.",
     "#pragma once", "namespace mgp {", "enum ParamId : int {"]
h += [f"  P_{p['id']}," for p in eng] + ["  P_COUNT", "};",
     "struct ParamMeta { const char* id; float min, max, def; };",
     "constexpr ParamMeta kParamMeta[P_COUNT] = {"]
h += [f'  {{"{p["id"]}", {float(p["min"])!r}f, {float(p["max"])!r}f, {float(p["def"])!r}f}},' for p in eng]
h += ["};", "}  // namespace mgp", ""]

t = ["// GENERATED by scripts/gen_params.py from shared/params.json - do not edit.",
     "export type ParamKind = 'knob' | 'toggle' | 'select';",
     "export type ParamGroup = 'amp' | 'str' | 'fx' | 'perf' | 'toggle' | 'select';",
     "export interface ParamDef {",
     "  id: ParamId; label: string; group: ParamGroup; kind: ParamKind;",
     "  min: number; max: number; def: number; step: number; unit?: string;",
     "  /** index in the native engine's parameter array, or -1 for UI-only parameters */",
     "  index: number;", "}",
     "export const PARAM_DEFS: readonly ParamDef[] = ["]
i = 0
for p in spec:
    idx = -1
    if p["engine"]:
        idx = i; i += 1
    u = f", unit: '{p['unit']}'" if "unit" in p else ""
    t.append(f"  {{id: '{p['id']}', label: '{p['label']}', group: '{p['group']}', kind: '{p['kind']}', "
             f"min: {num(p['min'])}, max: {num(p['max'])}, def: {num(p['def'])}, step: {num(p['step'])}{u}, index: {idx}}},")
t += ["];", f"export const ENGINE_PARAM_COUNT = {len(eng)};",
      "export type ParamId =" + "".join(f"\n  | '{p['id']}'" for p in spec) + ";", ""]

outs = {root / "native/cpp/ParamIds.h": "\n".join(h), root / "src/core/paramDefs.ts": "\n".join(t)}
if "--check" in sys.argv:
    bad = [str(p) for p, s in outs.items() if not p.exists() or p.read_text() != s]
    if bad:
        sys.exit("stale generated files (run scripts/gen_params.py): " + ", ".join(bad))
    print("generated params up to date")
else:
    for p, s in outs.items():
        p.write_text(s); print("wrote", p.relative_to(root))
